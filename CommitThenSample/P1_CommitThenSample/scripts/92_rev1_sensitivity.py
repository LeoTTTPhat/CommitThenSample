"""rev1 — E1 headline under the stream-recipe sensitivity variants (review R3-M1(a), task 6), side by side.

Reads results/summary/E1_summary_rev1{,_zq,_z0}.parquet (scripts/90_aggregate.py --exp E1 --rev rev1[_zq|_z0];
variant streams from P1-X-SV: zq = the infected host's zero-payload connections thinned with the stream's own payload
keep probability q; z0 = all of them removed) and writes results/summary/E1_recipe_sensitivity_rev1.json and a small
LaTeX table results/summary/E1_recipe_sensitivity_rev1.tex (LP-IoT23, p = 1 %, ρ = 5 %, content-evidence recall by
incident-size stratum with the k ≤ 20 cluster-bootstrap interval).

    .venv/bin/python -I P1_CommitThenSample/scripts/92_rev1_sensitivity.py
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import pandas as pd

P1 = Path(__file__).resolve().parents[1]
SUMMARY = P1 / "results" / "summary"
VARIANTS = (("original", "rev1"), ("zq", "rev1_zq"), ("z0", "rev1_z0"))
POLICIES = ("CtS-AI-static", "CtS-AI", "CtS-Size", "CtS-Unif", "DLT", "B13", "B4", "B3", "B6")
STRATA = ("k<=20", "k21-100", "k>100")


def _f(v):
    return None if v is None or (isinstance(v, float) and not math.isfinite(v)) else float(v)


def main() -> int:
    out = {"definition": "E1 rev1 content-evidence recall, LP-IoT23 group at target p = 1 % (6 LOSO folds), "
                         "rho = 5 % (and all rho in 'by_rho'), for the original streams and the two recipe variants "
                         "(zq: the infected host's zero-payload connections kept with the stream's payload keep "
                         "probability q, same seeds; z0: all removed, models retrained without the hosts' scans). "
                         "k<=20 interval = 95% two-stage cluster bootstrap over streams. Payload keep decisions are "
                         "identical across variants, so the incidents are the same (39/7/14).",
           "streams_q": {}, "rho5": {}, "by_rho": {}}
    idx = {}
    for v in ("zq", "z0"):
        f = P1 / "results" / "streams" / f"index_{v}.json"
        if f.exists():
            idx[v] = {r["stream_id"]: {k: r.get(k) for k in ("q", "zero_keep_prob", "n_seed_zero_units_before",
                                                             "n_seed_zero_units_after")}
                      for r in json.loads(f.read_text())["streams"] if r["kind"] == "lp_iot23"}
    out["streams_q"] = idx
    lines = []
    for name, tag in VARIANTS:
        p = SUMMARY / f"E1_summary_{tag}.parquet"
        if not p.exists():
            continue
        S = pd.read_parquet(p)
        g = S[S["group"] == "LP-IoT23 1%"]
        for pol in POLICIES:
            for rho, r in g[g["policy"] == pol].set_index("rho").iterrows():
                cell = {st: _f(r.get(f"content_{st}")) for st in STRATA}
                cell.update({"k<=20_lo": _f(r.get("content_k<=20_lo")), "k<=20_hi": _f(r.get("content_k<=20_hi")),
                             "presence_k<=20": _f(r.get("presence_k<=20")), "spend_over_target": _f(r.get("spend_over_target_mean")),
                             "n": [int(r.get(f"n_{st}", 0)) for st in STRATA]})
                out["by_rho"].setdefault(f"rho{rho:g}", {}).setdefault(pol, {})[name] = cell
                if abs(rho - 0.05) < 1e-12:
                    out["rho5"].setdefault(pol, {})[name] = cell
    for pol in POLICIES:
        row = out["rho5"].get(pol, {})
        cells = []
        for name, _ in VARIANTS:
            c = row.get(name)
            if c is None:
                cells.append("--")
                continue
            cells.append(f"{c['k<=20']:.2f} [{c['k<=20_lo']:.2f}, {c['k<=20_hi']:.2f}] / {c['k21-100']:.2f} / {c['k>100']:.2f}")
        lines.append(f"{pol} & " + " & ".join(cells) + "\\\\")
    tex = ["% generated by scripts/92_rev1_sensitivity.py (E1 rev1, LP-IoT23 p = 1%, rho = 5%)",
           "\\begin{tabular}{@{}l l l l@{}}", "\\toprule",
           "Policy & original & zq (scans thinned by $q$) & z0 (scan-free)\\\\", "\\midrule", *lines,
           "\\bottomrule", "\\end{tabular}"]
    (SUMMARY / "E1_recipe_sensitivity_rev1.tex").write_text("\n".join(tex) + "\n")
    (SUMMARY / "E1_recipe_sensitivity_rev1.json").write_text(json.dumps(out, indent=1))
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Table III rev1 (E1, ρ = 5%): equal-storage comparison with the rev1 (online / faithful) baselines, 95% cluster-
bootstrap intervals for the k ≤ 20 stratum, per-stream incident counts. LP-IoT23 (p = 1%, 6 LOSO folds) for the paper
table; LP-Edge for the supplement. The rev0 table (figures/tab3_e1.tex) is kept.

  figures/tab3_e1_rev1.tex        LaTeX rows (same column order as tab3_e1.tex plus an "online" flag column)
  figures/tab3_e1_rev1_edge.tex   LP-Edge rows
  figures/tab3_e1_rev1.caption.txt facts for caption and footnotes (values, CIs, per-stream counts, labels)

Input: results/summary/E1_summary_rev1.parquet, E1_numbers_rev1.json (scripts/90_aggregate.py --exp E1 --rev rev1).
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
P1 = HERE.parent
SUMMARY = P1 / "results" / "summary"
CK, X = "\\checkmark", "$\\times$"
# key, label, verifiable, unbiased, valid CI, online (no hindsight)
ROWS = [("CtS-AI-static", "CtS-AI, budget-matched$^{c}$", CK, CK, CK, CK),
        ("CtS-AI", "CtS-AI adaptive, as deployed$^{d}$", CK, CK, CK, CK),
        ("CtS-Size", "CtS-Size (B10, $\\pi\\propto\\sqrt{s}$)", CK, CK, CK, CK),
        ("DLT", "Threshold sampling (DLT, $\\pi=\\min(1,s/z)$)", CK + "$^{a}$", CK, "$\\sim^{g}$", CK),
        ("CtS-Unif", "CtS-Unif (B8)", CK, CK, CK, CK),
        ("B13", "Top-$k$ + keyed reserve (B13), online$^{e}$", CK + "$^{a}$", CK, CK, CK),
        ("B13-ctl", "\\quad B13, threshold controller$^{f}$", CK + "$^{a}$", CK, CK, CK),
        ("B13-offline", "\\quad B13, offline global top-$k$$^{h}$", X, CK, X, X),
        ("B2", "Ring buffer (B2)", X, X, X, CK),
        ("B3", "Time Machine (B3), byte level", X, X, X, CK),
        ("B3-unit", "\\quad B3, whole-unit scoring (rev0)", X, X, X, CK),
        ("B4", "Top-$k$ by $P_{\\mathrm{mal}}$ (B4), online$^{e}$", X, X, X, CK),
        ("B4-ctl", "\\quad B4, threshold controller$^{f}$", X, X, X, CK),
        ("B4-offline", "\\quad B4, offline global top-$k$$^{h}$", X, X, X, X),
        ("B6", "Alert-triggered (B6), 36 strict sids$^{i}$", X, X, X, CK),
        ("B6-allsids", "\\quad B6, all replay alerts (rev0)$^{i}$", X, X, X, CK),
        ("B15", "1:$N$ systematic (B15)$^{j}$", X, "$\\sim^{b}$", X, CK)]
STRATA = ("k<=20", "k21-100", "k>100")


def _nan(v):
    return v is None or (isinstance(v, float) and (math.isnan(v) or math.isinf(v)))


def fmt_rec(c, p, lo=None, hi=None):
    if _nan(c):
        return "--"
    s = f"{c:.2f}"
    if not _nan(lo) and not _nan(hi):
        s += f" [{lo:.2f}, {hi:.2f}]"
    if not _nan(p) and abs(p - c) >= 0.01:
        s += f" ({p:.2f})"
    return s


def fmt(v, nd=2):
    return "--" if _nan(v) else f"{v:.{nd}f}"


def rows_for(S: pd.DataFrame, group: str, rho: float = 0.05):
    g = S[(S["group"] == group) & (abs(S["rho"] - rho) < 1e-12)].set_index("policy")
    out, facts = [], {}
    for key, lab, ver, unb, ci, onl in ROWS:
        if key not in g.index:
            continue
        r = g.loc[key]
        rec = [fmt_rec(r.get(f"content_{STRATA[0]}"), r.get(f"presence_{STRATA[0]}"), r.get(f"content_{STRATA[0]}_lo"),
                       r.get(f"content_{STRATA[0]}_hi"))]
        rec += [fmt_rec(r.get(f"content_{st}"), r.get(f"presence_{st}")) for st in STRATA[1:]]
        sp = fmt(r.get("spend_over_target_mean"), 2)
        bias, rmse = r.get("rel_bias_median"), r.get("rel_rmse_median")
        br = "--" if _nan(bias) else f"{bias:+.2f} / {rmse:.2f}"
        mb = fmt(r.get("benign_MB_per_stream"), 0)
        out.append(f"{lab} & {rec[0]} & {rec[1]} & {rec[2]} & {mb} & {sp} & {br} & {ver} & {unb} & {ci} & {onl}\\\\")
        facts[key] = {k: (None if _nan(v) else v) for k, v in r.to_dict().items() if isinstance(v, (int, float, str))}
    return out, facts


def main() -> int:
    S = pd.read_parquet(SUMMARY / "E1_summary_rev1.parquet")
    nums = json.loads((SUMMARY / "E1_numbers_rev1.json").read_text())
    rows, facts = rows_for(S, "LP-IoT23 1%")
    (HERE / "tab3_e1_rev1.tex").write_text("% generated by figures/tab3_e1_rev1.py from results/summary/E1_summary_rev1.parquet\n"
                                           + "\n".join(rows) + "\n")
    rows_e, facts_e = rows_for(S, "LP-Edge")
    (HERE / "tab3_e1_rev1_edge.tex").write_text("% generated by figures/tab3_e1_rev1.py (LP-Edge, zero-shot; supplement)\n"
                                                + "\n".join(rows_e) + "\n")
    g = S[(S["group"] == "LP-IoT23 1%") & (abs(S["rho"] - 0.05) < 1e-12)]
    ge = S[(S["group"] == "LP-Edge") & (abs(S["rho"] - 0.05) < 1e-12)]
    cap = {"table": "Table III rev1 (tab:e1)", "rho": 0.05,
           "columns": "recall k<=20 [95% cluster-bootstrap CI] (presence), recall 21-100, recall >100, benign MB/stream, "
                      "spend/target, median rel. bias / median rel. RMSE, verifiable, unbiased, valid CI, online",
           "incidents_per_stratum": {st: int(g[f"n_{st}"].max()) for st in STRATA},
           "incidents_per_stratum_edge": {st: int(ge[f"n_{st}"].max()) for st in STRATA},
           "per_stream_incidents": nums.get("per_stream_incidents"),
           "clusters_k<=20": {"LP-IoT23": int(g["n_clusters_k<=20"].max()) if "n_clusters_k<=20" in g else None,
                              "LP-Edge": int(ge["n_clusters_k<=20"].max()) if "n_clusters_k<=20" in ge else None},
           "footnotes": {
               "a": "with a committed seed / committed scores",
               "b": "unbiased for packet-additive counts over the random offset, not for unit-level indicators",
               "c": "budget-matched static U5tau0.2 (fixed lambda, expected spend = B-bar E): the equal-storage CtS row",
               "d": "adaptive arm as deployed (realised-cost controller + boost), R = 200 reps x 3 seeds of the exact "
                    "full-unit simulation; spend/target = realised mean (not budget-matched)",
               "e": "online, budget-exact: per epoch the highest-P_mal payload units (greedy) within B-bar + the carried "
                    "unspent budget; B13 keeps a keyed reserve pi_r,e = max(phi0, (B_e - top)/Sum_rest s) on the other "
                    "units, computed from the epoch's own committed metadata (predictable, so HT and both CSs are valid)",
               "f": "online horizon threshold controller (kappa = 1, W_c = 30, L = ln 16) whose reference threshold is "
                    "calibrated on the fold's TRAINING streams; not budget-matched (spend/target column)",
               "g": "valid HT and lower CS; no floor, so the upper CS is uninformative (c-bar unbounded)",
               "h": "global top-k over the whole test stream (hindsight; rev0 rows): not online, and B13's reserve rate "
                    "depends on the whole stream, so its pi are not predictable (no valid statements)",
               "i": "bias/RMSE on detector (D) estimands only",
               "j": "recall = P(>= 1 packet of a content unit sampled) (upper bound on content evidence); natural "
                    "estimator not scored"},
           "labels": nums.get("policy_labels"), "values": facts, "values_edge": facts_e}
    (HERE / "tab3_e1_rev1.caption.txt").write_text(json.dumps(cap, indent=1, default=str))
    print("\n".join(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())

"""Table III (E1, ρ = 5%): equal-budget comparison on LP-IoT23 (p = 1%, 6 LOSO folds); LP-Edge variant for the
supplement. Writes LaTeX row blocks matching paper/sections/08_evaluation.tex (Table tab:e1):

  figures/tab3_e1.tex        rows for LP-IoT23 1% (the paper table)
  figures/tab3_e1_edge.tex   rows for LP-Edge (zero-shot; supplement)
  figures/tab3_e1.caption.txt  facts for the caption / footnotes

Cells: content-evidence recall by incident-size stratum (presence recall in parentheses where it differs by >= 0.01),
benign MB retained per stream, spend/target (realised mean for the adaptive arm), median relative bias / median
relative RMSE of the policy's natural estimator over (stream, estimand) pairs with Q > 0.
"""
from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
P1 = HERE.parent
SUMMARY = P1 / "results" / "summary"

ROWS = [("CtS-AI", "CtS-AI (U6$\\tau$)$^{c}$", "\\checkmark", "\\checkmark", "\\checkmark"),
        ("CtS-AI-static", "CtS-AI static, matched$^{d}$", "\\checkmark", "\\checkmark", "\\checkmark"),
        ("CtS-Size", "CtS-Size (B10)", "\\checkmark", "\\checkmark", "\\checkmark"),
        ("CtS-Unif", "CtS-Unif (B8)", "\\checkmark", "\\checkmark", "\\checkmark"),
        ("B13", "Top-$k$ + keyed reserve (B13)", "\\checkmark$^{a}$", "\\checkmark", "\\checkmark"),
        ("B2", "Ring buffer (B2)", "$\\times$", "$\\times$", "$\\times$"),
        ("B3", "Time Machine (B3)", "$\\times$", "$\\times$", "$\\times$"),
        ("B4", "Top-$k$ by $P_{\\mathrm{mal}}$ (B4)", "$\\times$", "$\\times$", "$\\times$"),
        ("B6", "Alert-triggered (B6)$^{e}$", "$\\times$", "$\\times$", "$\\times$"),
        ("B15", "1:$N$ systematic (B15)$^{f}$", "$\\times$", "$\\sim^{b}$", "$\\times$")]
STRATA = ("k<=20", "k21-100", "k>100")


def fmt_rec(c, p):
    if c is None or (isinstance(c, float) and math.isnan(c)):
        return "--"
    s = f"{c:.2f}"
    if p is not None and not (isinstance(p, float) and math.isnan(p)) and abs(p - c) >= 0.01:
        s += f" ({p:.2f})"
    return s


def fmt(v, nd=2):
    if v is None or (isinstance(v, float) and (math.isnan(v) or math.isinf(v))):
        return "--"
    return f"{v:.{nd}f}"


def rows_for(S: pd.DataFrame, group: str, rho: float = 0.05) -> tuple[list[str], dict]:
    g = S[(S["group"] == group) & (abs(S["rho"] - rho) < 1e-12)].set_index("policy")
    out, facts = [], {}
    for key, lab, ver, unb, ci in ROWS:
        if key not in g.index:
            continue
        r = g.loc[key]
        rec = [fmt_rec(r.get(f"content_{st}"), r.get(f"presence_{st}")) for st in STRATA]
        sp = fmt(r.get("spend_over_target_mean"), 2)
        if key == "CtS-AI":
            sp = f"{r.get('spend_over_target_mean'):.2f}"
        bias = r.get("rel_bias_median")
        rmse = r.get("rel_rmse_median")
        br = "--" if (bias is None or (isinstance(bias, float) and math.isnan(bias))) else f"{bias:+.2f} / {rmse:.2f}"
        mb = fmt(r.get("benign_MB_per_stream"), 0)
        out.append(f"{lab} & {rec[0]} & {rec[1]} & {rec[2]} & {mb} & {sp} & {br} & {ver} & {unb} & {ci}\\\\")
        facts[key] = {k: (None if isinstance(v, float) and math.isnan(v) else v) for k, v in r.to_dict().items()
                      if isinstance(v, (int, float, str))}
    return out, facts


def main() -> int:
    S = pd.read_parquet(SUMMARY / "E1_summary.parquet")
    rows, facts = rows_for(S, "LP-IoT23 1%")
    (HERE / "tab3_e1.tex").write_text("% generated by figures/tab3_e1.py from results/summary/E1_summary.parquet\n"
                                      + "\n".join(rows) + "\n")
    rows_e, facts_e = rows_for(S, "LP-Edge")
    (HERE / "tab3_e1_edge.tex").write_text("% generated by figures/tab3_e1.py (LP-Edge, zero-shot; supplement)\n"
                                           + "\n".join(rows_e) + "\n")
    g = S[(S["group"] == "LP-IoT23 1%") & (abs(S["rho"] - 0.05) < 1e-12)]
    n = {st: int(g[f"n_{st}"].max()) for st in STRATA}
    ge = S[(S["group"] == "LP-Edge") & (abs(S["rho"] - 0.05) < 1e-12)]
    cap = {"table": "Table III (tab:e1)", "rho": 0.05, "streams": "LP-IoT23, 6 LOSO folds at target p = 1% (realised "
           "0.41-1.05%)", "incidents_per_stratum": n, "incidents_per_stratum_edge": {st: int(ge[f"n_{st}"].max()) for st in STRATA},
           "footnotes": {
               "a": "with a committed seed",
               "b": "unbiased for packet-additive counts over the random offset, not for unit-level indicators",
               "c": "adaptive arm as deployed (realised-cost controller + boost), R = 200 reps x 3 seeds of the exact "
                    "full-unit simulation; spend/target = realised mean (not budget-matched)",
               "d": "budget-matched static U5tau (fixed lambda, expected spend = B-bar E)",
               "e": "bias/RMSE on detector (D) estimands only",
               "f": "recall = P(>= 1 packet of a content unit sampled) (upper bound on content evidence); natural estimator "
                    "not scored"},
           "cells": "recall = content-evidence recall (presence recall in parentheses where different by >= 0.01); "
                    "benign MB retained per stream (expected); spend/target; median relative bias / median relative RMSE "
                    "of the natural estimator over (stream, estimand) pairs with Q > 0 (HT for CtS/B13; sum of retained "
                    "for B2/B3/B4/B6)",
           "values": facts, "values_edge": facts_e}
    (HERE / "tab3_e1.caption.txt").write_text(json.dumps(cap, indent=1, default=str))
    print("\n".join(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
